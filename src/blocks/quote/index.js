/**
 * Registers a new block provided a unique name and an object defining its behavior.
 *
 * @see https://developer.wordpress.org/block-editor/reference-guides/block-api/block-registration/
 */
import { registerBlockType } from '@wordpress/blocks';
import advancedOptionsAttributes from '../../constants/advancedOptionsAttributes';
import layoutOptionsAttributes from '../../constants/layoutOptionsAttributes';

/**
 * Internal dependencies
 */
import Edit from './edit';
import save from './save';
import metadata from './block.json';

const quoteIcon = (
	<svg
		viewBox="0 0 24 24"
		xmlns="http://www.w3.org/2000/svg"
		aria-hidden="true"
		focusable="false"
	>
		<path d="M7 5a4 4 0 014 4v6a4 4 0 01-4 4H5a4 4 0 01-4-4v-6a4 4 0 014-4h2zm12 0a4 4 0 014 4v6a4 4 0 01-4 4h-2a4 4 0 01-4-4v-6a4 4 0 014-4h2z"></path>
	</svg>
);

/**
 * Every block starts by registering a new block type definition.
 *
 * @see https://developer.wordpress.org/block-editor/reference-guides/block-api/block-registration/
 */
registerBlockType( metadata.name, {
	icon: quoteIcon,

	// Merge attributes from block.json and the shared option constants.
	attributes: {
		...metadata.attributes,
		...advancedOptionsAttributes,
		...layoutOptionsAttributes,
	},

	/**
	 * @see ./edit.js
	 */
	edit: Edit,

	/**
	 * @see ./save.js
	 */
	save,
} );
